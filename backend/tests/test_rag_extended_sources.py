def test_rerank_hits_prefers_keyword_overlap() -> None:
    from app.infrastructure.database.knowledge_repository import (
        RagHit,
        rerank_hits,
    )

    overlapping = RagHit(
        evidence_id="a",
        source_type="social_post",
        source_id="1",
        content="新能源汽车召回引发热议",
        score=0.5,
    )
    unrelated = RagHit(
        evidence_id="b",
        source_type="social_post",
        source_id="2",
        content="今天天气不错适合出行",
        score=0.5,
    )
    result = rerank_hits(
        [overlapping, unrelated],
        query_terms=["新能源", "召回"],
        limit=2,
    )
    assert result[0].evidence_id == "a"
    assert result[0].score > result[1].score


def test_api_evidence_search_platform_filter(tmp_path: Path) -> None:
    from fastapi.testclient import TestClient

    from app.core.config import Settings
    from app.main import create_app

    app = create_app(
        Settings(
            database_url=f"sqlite+aiosqlite:///{tmp_path / 'api.db'}",
            demo_mode=True,
        )
    )
    with TestClient(app) as client:
        case = client.post(
            "/api/v1/cases",
            json={"topic": "新能源汽车争议", "platforms": ["weibo", "bilibili"]},
        ).json()
        case_id = case["id"]
        client.post(
            f"/api/v1/cases/{case_id}/memories",
            json={
                "kind": "fact",
                "content": "微博官方账号发布召回公告",
                "source_type": "social_post",
                "source_id": "p1",
            },
        )
        hits = client.post(
            f"/api/v1/cases/{case_id}/evidence/search",
            json={"query": "召回", "limit": 5, "platforms": ["bilibili"]},
        )
        assert hits.status_code == 200
        returned = hits.json()
        # Platform filtering applies to social sources only; the memory row
        # has no platform column and is not filtered out.
        assert len(returned) == 1
        assert returned[0]["source_type"] == "memory"
        time_hits = client.post(
            f"/api/v1/cases/{case_id}/evidence/search",
            json={
                "query": "召回",
                "limit": 5,
                "time_range": {"from": "2026-08-01T00:00:00+00:00"},
            },
        )
        assert time_hits.status_code == 200
        assert len(time_hits.json()) == 1
